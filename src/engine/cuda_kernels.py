"""Single-launch CUDA C++ ``float64`` Thomas / Takahashi / Cholesky kernels.

Contract (readme Sections 4.8, 5.3.4.5): thread-per-cell CUDA kernels via
``torch.utils.cpp_extension.load_inline`` eliminating the 9,510-iteration
per-``t`` kernel-launch bottleneck of the pure-PyTorch loop, automatically
falling back to ``thomas_takahashi.py`` (the CPU reference) whenever CUDA or
``nvcc`` is unavailable.  The CUDA path is verified bit-for-bit (< 1e-10)
against the CPU reference in ``tests/test_06_gpu_solver_math.py``.

Build / dispatch contract
-------------------------
* Python bindings are generated by ``load_inline(functions=[...])`` from the
  C++ prototypes in ``_CPP_SOURCE``; the CUDA translation unit therefore
  contains NO ``PYBIND11_MODULE`` (a second module definition is a duplicate
  symbol and the build fails).
* Every host entry point installs a ``c10::cuda::CUDAGuard`` on the input
  tensor's device and launches on that device's current stream, so the
  kernels run on whichever ``cuda:k`` (k = 0..3 on a 4x L4 node) owns the
  solver chunk.  Outputs stay on the caller's device (no ``.cpu()``
  round-trips inside the Newton loop).
* Memory layout: kernels work on time-major ``(T, B)`` buffers so that
  consecutive threads (cells) touch consecutive addresses at every step
  ``t`` (coalesced loads); the sampler runs one thread per (cell, sample)
  pair on ``(B, T, M)`` buffers (consecutive threads = consecutive ``m``).
  The arithmetic is exactly the reference recursion (same operation order),
  so results agree with the CPU reference to round-off.
"""
from __future__ import annotations

import os
import threading

import torch

from .thomas_takahashi import (joint_cholesky_sample as _cpu_sample,
                               takahashi_marginals as _cpu_takahashi,
                               thomas_factor as _cpu_factor,
                               thomas_factor_and_solve as _cpu_thomas)

_DIAG_FLOOR = 1e-7
_LOCK = threading.Lock()
_MODULE = None
_COMPILE_ERROR = None

_CPP_SOURCE = r"""
#include <torch/extension.h>
#include <vector>

std::vector<torch::Tensor> thomas_solve_cuda(torch::Tensor a, torch::Tensor b,
                                             torch::Tensor g);
std::vector<torch::Tensor> thomas_factor_cuda(torch::Tensor a, torch::Tensor b);
std::vector<torch::Tensor> takahashi_cuda(torch::Tensor l, torch::Tensor d);
torch::Tensor cholesky_sample_cuda(torch::Tensor l, torch::Tensor d,
                                   torch::Tensor eps);
"""

_CUDA_SOURCE = r"""
#include <torch/extension.h>
#include <ATen/cuda/CUDAContext.h>
#include <c10/cuda/CUDAGuard.h>
#include <cmath>
#include <vector>

#define DIAG_FLOOR 1e-7

// ---------------------------------------------------------------------------
// Thread-per-cell batched Thomas LDL^T factor (+ optional solve).
// Time-major buffers: a,d,g,dz: (T, B); b,l: (T-1, B).  Thread `row` owns
// column `row`; at each step t all threads read a contiguous row (coalesced).
// ---------------------------------------------------------------------------
__global__ void thomas_kernel(const double* __restrict__ a,
                              const double* __restrict__ b,
                              const double* __restrict__ g,
                              double* __restrict__ l,
                              double* __restrict__ d,
                              double* __restrict__ dz,
                              int64_t B, int64_t T, bool do_solve) {
    int64_t row = (int64_t)blockIdx.x * blockDim.x + threadIdx.x;
    if (row >= B) return;
    double d_prev = a[row];
    d[row] = d_prev;
    for (int64_t t = 0; t < T - 1; ++t) {
        double bt = b[t * B + row];
        double lt = bt / d_prev;
        l[t * B + row] = lt;
        double dn = a[(t + 1) * B + row] - lt * bt;
        d_prev = dn > DIAG_FLOOR ? dn : DIAG_FLOOR;
        d[(t + 1) * B + row] = d_prev;
    }
    if (!do_solve) return;
    // forward substitution L y = g (y stored in dz)
    double y_prev = g[row];
    dz[row] = y_prev;
    for (int64_t t = 1; t < T; ++t) {
        y_prev = g[t * B + row] - l[(t - 1) * B + row] * y_prev;
        dz[t * B + row] = y_prev;
    }
    // backward substitution D L^T dz = y
    double z_next = dz[(T - 1) * B + row] / d[(T - 1) * B + row];
    dz[(T - 1) * B + row] = z_next;
    for (int64_t t = T - 2; t >= 0; --t) {
        z_next = dz[t * B + row] / d[t * B + row] - l[t * B + row] * z_next;
        dz[t * B + row] = z_next;
    }
}

// ---------------------------------------------------------------------------
// Thread-per-cell Takahashi marginals (time-major):
// sig_d (T, B), sig_l (T-1, B).
// ---------------------------------------------------------------------------
__global__ void takahashi_kernel(const double* __restrict__ l,
                                 const double* __restrict__ d,
                                 double* __restrict__ sig_d,
                                 double* __restrict__ sig_l,
                                 int64_t B, int64_t T) {
    int64_t row = (int64_t)blockIdx.x * blockDim.x + threadIdx.x;
    if (row >= B) return;
    double s_next = 1.0 / d[(T - 1) * B + row];
    sig_d[(T - 1) * B + row] = s_next;
    for (int64_t t = T - 2; t >= 0; --t) {
        double lt = l[t * B + row];
        double sl = -lt * s_next;
        sig_l[t * B + row] = sl;
        s_next = 1.0 / d[t * B + row] - lt * sl;
        sig_d[t * B + row] = s_next;
    }
}

// ---------------------------------------------------------------------------
// Joint Cholesky sampling L^T u = D^{-1/2} eps, one thread per (cell, m):
// l (B, T-1), d (B, T) row-major; eps/u (B, T, M).  Consecutive threads
// handle consecutive m -> coalesced eps/u traffic.
// ---------------------------------------------------------------------------
__global__ void cholesky_sample_kernel(const double* __restrict__ l,
                                       const double* __restrict__ d,
                                       const double* __restrict__ eps,
                                       double* __restrict__ u,
                                       int64_t B, int64_t T, int64_t M) {
    int64_t tid = (int64_t)blockIdx.x * blockDim.x + threadIdx.x;
    if (tid >= B * M) return;
    int64_t row = tid / M;
    int64_t m = tid - row * M;
    const double* lrow = l + row * (T - 1);
    const double* drow = d + row * T;
    const double* erow = eps + row * T * M;
    double* urow = u + row * T * M;
    double u_next = erow[(T - 1) * M + m] / sqrt(drow[T - 1]);
    urow[(T - 1) * M + m] = u_next;
    for (int64_t t = T - 2; t >= 0; --t) {
        u_next = erow[t * M + m] / sqrt(drow[t]) - lrow[t] * u_next;
        urow[t * M + m] = u_next;
    }
}

static void check_cuda_f64(const torch::Tensor& x, const char* name) {
    TORCH_CHECK(x.is_cuda(), name, " must be a CUDA tensor");
}

std::vector<torch::Tensor> thomas_run(torch::Tensor a, torch::Tensor b,
                                      torch::Tensor g, bool do_solve) {
    check_cuda_f64(a, "a");
    check_cuda_f64(b, "b");
    const c10::cuda::CUDAGuard device_guard(a.device());
    auto opts = a.options().dtype(torch::kDouble);
    int64_t B = a.size(0);
    int64_t T = a.size(1);
    // time-major copies for coalesced access
    auto aT = a.to(torch::kDouble).t().contiguous();
    auto bT = b.to(a.device(), torch::kDouble).t().contiguous();
    torch::Tensor gT;
    if (do_solve) {
        check_cuda_f64(g, "g");
        gT = g.to(a.device(), torch::kDouble).t().contiguous();
    } else {
        gT = torch::zeros({1, 1}, opts);
    }
    int64_t Tm1 = T > 1 ? T - 1 : 1;
    auto lT = torch::zeros({Tm1, B}, opts);
    auto dT = torch::empty({T, B}, opts);
    auto zT = do_solve ? torch::empty({T, B}, opts) : torch::zeros({1, 1}, opts);
    if (B > 0 && T >= 2) {
        const int threads = 128;
        const int blocks = (int)((B + threads - 1) / threads);
        thomas_kernel<<<blocks, threads, 0,
                        at::cuda::getCurrentCUDAStream()>>>(
            aT.data_ptr<double>(), bT.data_ptr<double>(),
            gT.data_ptr<double>(), lT.data_ptr<double>(),
            dT.data_ptr<double>(), zT.data_ptr<double>(), B, T, do_solve);
        C10_CUDA_KERNEL_LAUNCH_CHECK();
    } else if (B > 0) {   // T == 1: d = max(a, floor); dz = g / d
        dT.copy_(aT.clamp_min(DIAG_FLOOR));
        if (do_solve) zT.copy_(gT / dT);
    }
    auto l = lT.t().contiguous();
    auto d = dT.t().contiguous();
    if (do_solve) {
        return {zT.t().contiguous(), l, d};
    }
    return {l, d};
}

std::vector<torch::Tensor> thomas_solve_cuda(torch::Tensor a, torch::Tensor b,
                                             torch::Tensor g) {
    return thomas_run(a, b, g, true);
}

std::vector<torch::Tensor> thomas_factor_cuda(torch::Tensor a, torch::Tensor b) {
    return thomas_run(a, b, a, false);
}

std::vector<torch::Tensor> takahashi_cuda(torch::Tensor l, torch::Tensor d) {
    check_cuda_f64(l, "l");
    check_cuda_f64(d, "d");
    const c10::cuda::CUDAGuard device_guard(d.device());
    auto opts = d.options().dtype(torch::kDouble);
    int64_t B = d.size(0);
    int64_t T = d.size(1);
    auto lT = l.to(d.device(), torch::kDouble).t().contiguous();
    auto dT = d.to(torch::kDouble).t().contiguous();
    auto sdT = torch::empty({T, B}, opts);
    auto slT = torch::zeros({T > 1 ? T - 1 : 1, B}, opts);
    if (B > 0 && T >= 2) {
        const int threads = 128;
        const int blocks = (int)((B + threads - 1) / threads);
        takahashi_kernel<<<blocks, threads, 0,
                           at::cuda::getCurrentCUDAStream()>>>(
            lT.data_ptr<double>(), dT.data_ptr<double>(),
            sdT.data_ptr<double>(), slT.data_ptr<double>(), B, T);
        C10_CUDA_KERNEL_LAUNCH_CHECK();
    } else if (B > 0) {
        sdT.copy_(1.0 / dT);
    }
    return {sdT.t().contiguous(), slT.t().contiguous()};
}

torch::Tensor cholesky_sample_cuda(torch::Tensor l, torch::Tensor d,
                                   torch::Tensor eps) {
    check_cuda_f64(l, "l");
    check_cuda_f64(d, "d");
    check_cuda_f64(eps, "eps");
    const c10::cuda::CUDAGuard device_guard(eps.device());
    auto l_c = l.to(eps.device(), torch::kDouble).contiguous();
    auto d_c = d.to(eps.device(), torch::kDouble).contiguous();
    auto eps_c = eps.to(torch::kDouble).contiguous();
    int64_t B = eps_c.size(0);
    int64_t T = eps_c.size(1);
    int64_t M = eps_c.size(2);
    auto u = torch::empty_like(eps_c);
    if (B > 0 && T >= 2 && M > 0) {
        const int threads = 256;
        const int64_t total = B * M;
        const int blocks = (int)((total + threads - 1) / threads);
        cholesky_sample_kernel<<<blocks, threads, 0,
                                 at::cuda::getCurrentCUDAStream()>>>(
            l_c.data_ptr<double>(), d_c.data_ptr<double>(),
            eps_c.data_ptr<double>(), u.data_ptr<double>(), B, T, M);
        C10_CUDA_KERNEL_LAUNCH_CHECK();
    } else if (B > 0 && M > 0) {
        u.copy_(eps_c / d_c.sqrt().unsqueeze(-1));
    }
    return u;
}
"""

_FUNCTIONS = ["thomas_solve_cuda", "thomas_factor_cuda", "takahashi_cuda",
              "cholesky_sample_cuda"]


def build_module(verbose: bool = False, force: bool = False):
    """Compile (or load from the torch extension cache) the inline module.

    Does not require a visible GPU (only ``nvcc`` + CUDA headers), so the
    build itself can be verified on a CPU host with a CUDA toolkit.
    """
    from torch.utils.cpp_extension import load_inline
    extra_cuda = ["-O3"]
    return load_inline(
        name="fire_harmonizer_cuda_kernels_v2",
        cpp_sources=[_CPP_SOURCE],
        cuda_sources=[_CUDA_SOURCE],
        functions=_FUNCTIONS,
        extra_cuda_cflags=extra_cuda,
        verbose=verbose,
        keep_intermediates=False,
    )


def _try_compile():
    """Lazily compile the inline extension (once per process)."""
    global _MODULE, _COMPILE_ERROR
    if _MODULE is not None or _COMPILE_ERROR is not None:
        return
    if not torch.cuda.is_available():
        _COMPILE_ERROR = RuntimeError("CUDA not available")
        return
    try:
        _MODULE = build_module(
            verbose=bool(os.environ.get("FIRE_HARMONIZER_CUDA_VERBOSE")))
    except Exception as exc:  # noqa: BLE001 - CPU fallback per contract
        _COMPILE_ERROR = exc


def cuda_available() -> bool:
    with _LOCK:
        _try_compile()
    return _MODULE is not None


def compile_error():
    """The exception raised by the last failed build (None if OK/untried)."""
    return _COMPILE_ERROR


def _cuda_target(x: torch.Tensor) -> torch.device:
    """Device the kernel runs on: the input's own CUDA device, or the
    current CUDA device for CPU inputs."""
    if x.is_cuda:
        return x.device
    return torch.device("cuda", torch.cuda.current_device())


def _want(use_cuda):
    want = use_cuda if use_cuda is not None else cuda_available()
    if want:
        with _LOCK:
            _try_compile()
    return bool(want) and _MODULE is not None


def thomas_solve_batched(a, b, g, use_cuda: bool | None = None):
    """Batched Thomas solve with transparent CUDA/CPU dispatch.

    Returns (dz, l, d) in ``torch.float64`` on the device of ``a``.
    """
    if _want(use_cuda):
        dev = _cuda_target(a)
        dz, l, d = _MODULE.thomas_solve_cuda(
            a.to(dev, torch.float64), b.to(dev, torch.float64),
            g.to(dev, torch.float64))
        return dz.to(a.device), l.to(a.device), d.to(a.device)
    out = _cpu_thomas(a.to(torch.float64), b.to(torch.float64),
                      g.to(torch.float64))
    return out


def thomas_factor_batched(a, b, use_cuda: bool | None = None):
    """Batched LDL^T factorization only. Returns (l, d) on ``a``'s device."""
    if _want(use_cuda):
        dev = _cuda_target(a)
        l, d = _MODULE.thomas_factor_cuda(a.to(dev, torch.float64),
                                          b.to(dev, torch.float64))
        return l.to(a.device), d.to(a.device)
    return _cpu_factor(a.to(torch.float64), b.to(torch.float64))


def takahashi_batched(l, d, use_cuda: bool | None = None):
    """Batched Takahashi marginals with transparent dispatch."""
    if _want(use_cuda):
        dev = _cuda_target(d)
        sig_d, sig_l = _MODULE.takahashi_cuda(l.to(dev, torch.float64),
                                              d.to(dev, torch.float64))
        return sig_d.to(d.device), sig_l.to(d.device)
    return _cpu_takahashi(l.to(torch.float64), d.to(torch.float64))


def cholesky_sample_batched(l, d, eps, use_cuda: bool | None = None):
    """Batched joint Cholesky sampling with transparent dispatch."""
    if _want(use_cuda):
        dev = _cuda_target(eps)
        u = _MODULE.cholesky_sample_cuda(l.to(dev, torch.float64),
                                         d.to(dev, torch.float64),
                                         eps.to(dev, torch.float64))
        return u.to(eps.device)
    return _cpu_sample(l.to(torch.float64), d.to(torch.float64),
                       eps.to(torch.float64))


def reset_module() -> None:
    """Reset the compiled-module cache (tests)."""
    global _MODULE, _COMPILE_ERROR
    with _LOCK:
        _MODULE = None
        _COMPILE_ERROR = None
